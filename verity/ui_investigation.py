"""Streamlit presentation for evidence; untrusted text is never interpreted as HTML."""

from dataclasses import asdict

import streamlit as st

from verity.models import Investigation


def render_investigation(result: Investigation) -> None:
    st.subheader("Investigation findings")
    st.caption(f"{result.mode} · {result.elapsed_seconds:.2f}s" + (f" · {result.model}" if result.model else ""))
    st.warning("Identity unverified · Human review required · No payment recommendation in Phase 2")
    alerts = sum(f.severity == "alert" for f in result.findings)
    reviews = sum(f.severity == "review" for f in result.findings)
    for column, label, value in zip(st.columns(3), ["Alerts", "Review items", "Tools completed"], [alerts, reviews, len(result.tool_trace)]):
        column.metric(label, value)
    st.caption("Counts are not a fraud probability or risk score. A directory match cannot establish who sent a message.")
    st.markdown("#### Evidence summary")
    # Only display sentences generated by local tools; the AI may select IDs, not invent facts.
    for finding in result.findings:
        if finding.code in result.highlights:
            st.text(f"• {finding.message}")
    evidence, details, trace = st.tabs(["All findings", "Request & matched records", "Tool activity"])
    with evidence:
        st.dataframe([asdict(f) for f in result.findings], hide_index=True, width="stretch")
    with details:
        st.markdown("**Investigated request**")
        st.code(result.request_text, language=None)
        st.markdown("**Extracted details**")
        st.json({**result.parsed.extraction.model_dump(), "amount_cents": result.parsed.amount_cents, "warnings": result.parsed.warnings})
        st.markdown("**Directory record (not identity verification)**")
        st.json(result.employee or {"status": "No match"})
        st.markdown("**Vendor record**")
        st.json(result.vendor or {"status": "No match"})
    with trace:
        st.caption("These are actual local tool results. Offline mode runs them without a model. Live mode uses constrained model tool calls.")
        for entry in result.tool_trace:
            with st.expander(entry["tool"] + " · " + entry["status"]):
                st.json(entry["result"])
    st.caption("Results are kept in this session only. Simulated verification, final decisions, and audit persistence arrive in Phase 3.")
